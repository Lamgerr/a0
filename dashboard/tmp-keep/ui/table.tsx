interface TableHeadProps extends React.ThHTMLAttributes<HTMLTableCellElement> {
  sortable?: boolean
  sorted?: 'asc' | 'desc' | null
  onSort?: () => void
}

const TableHead = React.forwardRef<HTMLTableCellElement, TableHeadProps>(
  ({ className, children, sortable, sorted, onSort, ...props }, ref) => (
    <th
      ref={ref}
      className={cn(
        "h-10 px-4 text-left align-middle font-medium text-muted-foreground/70 text-xs uppercase tracking-wider [&:has([role=checkbox])]:pr-0 relative",
        sortable && "cursor-pointer select-none",
        className
      )}
      onClick={sortable ? onSort : undefined}
      {...props}
    >
      <div className="flex items-center gap-1.5">
        {children}
        {sortable && (
          <div className="flex flex-col gap-px ml-0.5">
            <span 
              className={cn("h-1 w-1 border-t border-r rotate-45 transform transition-colors", 
                sorted === 'asc' ? "border-current text-foreground" : "border-muted-foreground/30"
              )}
            />
            <span 
              className={cn("h-1 w-1 border-b border-l -rotate-45 transform transition-colors",
                sorted === 'desc' ? "border-current text-foreground" : "border-muted-foreground/30"
              )}
            />
          </div>
        )}
      </div>
    </th>
  )
)
TableHead.displayName = "TableHead"

